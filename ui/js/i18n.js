let LANG = localStorage.getItem('ui_lang') || 'ru';

function t(key, fallback) {
  const d = I18N[LANG] || I18N.ru;
  if (d[key] !== undefined && d[key] !== null) return d[key];
  if (I18N.ru[key] !== undefined && I18N.ru[key] !== null) return I18N.ru[key];
  return fallback !== undefined ? fallback : key;
}

const CAT_KEYS = ['communication','meetings','documents','analytics','hr_team','negotiations','stress','ethics','emotional','adversarial'];
const CRIT_KEYS = ['accuracy','completeness','instruction_following','practicality','tone_style','structure','conciseness','safety','ethical_soundness','autonomy'];

function catLabel(c) {
  const d = I18N[LANG] || I18N.ru;
  const k = 'cat_' + c;
  if (d[k] !== undefined && d[k] !== null) return d[k];
  if (I18N.ru[k] !== undefined && I18N.ru[k] !== null) return I18N.ru[k];
  return c;
}

function critLabel(c) {
  const d = I18N[LANG] || I18N.ru;
  const k = 'crit_' + c;
  if (d[k] !== undefined && d[k] !== null) return d[k];
  if (I18N.ru[k] !== undefined && I18N.ru[k] !== null) return I18N.ru[k];
  return c;
}

const CAT = new Proxy({}, {
  get: (_, c) => catLabel(c),
  ownKeys: () => CAT_KEYS,
  has: (_, c) => CAT_KEYS.includes(c),
  getOwnPropertyDescriptor: (_, c) => CAT_KEYS.includes(c) ? { value: catLabel(c), enumerable: true, configurable: true } : undefined
});

const CRIT = new Proxy({}, {
  get: (_, c) => critLabel(c),
  ownKeys: () => CRIT_KEYS,
  has: (_, c) => CRIT_KEYS.includes(c),
  getOwnPropertyDescriptor: (_, c) => CRIT_KEYS.includes(c) ? { value: critLabel(c), enumerable: true, configurable: true } : undefined
});

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.documentElement.lang = LANG;
}

function setLang(lang) {
  LANG = lang;
  localStorage.setItem('ui_lang', lang);
  applyI18n();
  const active = document.querySelector('.nav-item.active');
  if (active) nav(active.dataset.page, active);
}
